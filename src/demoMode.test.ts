import { afterAll, beforeAll, describe, expect, it, vi } from 'vitest'
import 'fake-indexeddb/auto'
import Dexie from 'dexie'

describe('demo bootstrap safety', () => {
  beforeAll(() => {
    window.history.replaceState(null, '', '/?demo=1&embed=1&theme=dark')
    vi.stubEnv('VITE_PUBLIC_SCHEDULE_PATH', '/private.sleepy')
    vi.stubEnv('VITE_PUBLIC_ACCESS_KEY_HASH', 'private-access-hash')
    vi.resetModules()
  })
  afterAll(async () => {
    const { db } = await import('./data/db')
    await db.delete()
    vi.unstubAllEnvs()
    window.history.replaceState(null, '', '/')
  })

  it('bypasses public access and never fetches the private public-schedule payload', async () => {
    const access = await import('./publicAccess')
    const schedule = await import('./publicSchedule')
    const fetch = vi.spyOn(window, 'fetch')
    expect(access.publicAccessRequired()).toBe(false)
    expect(access.publicAccessGranted()).toBe(true)
    expect(await access.grantPublicAccess('')).toBe(true)
    expect(schedule.publicScheduleEnabled()).toBe(false)
    expect(await schedule.loadPublicSchedule()).toBe(false)
    expect(fetch).not.toHaveBeenCalled()
    fetch.mockRestore()
  })

  it('seeds real sample courses atomically, reanchors an aged demo, and leaves the real database intact', async () => {
    const real = new Dexie('sleepy')
    real.version(1).stores({ prefs: 'key' })
    await real.table('prefs').put({ key: 'sentinel', value: 'real-user' })
    const { db, loadPrefs } = await import('./data/db')
    const { seedDemoTable } = await import('./data/sampleTable')
    const { inWeek } = await import('./data/types')
    expect(db.name).toBe('sleepy-demo-v1')
    await Promise.all([seedDemoTable(), seedDemoTable()])
    expect(await db.timetables.count()).toBe(1)
    expect(await db.courses.count()).toBe(9)
    const table = (await db.timetables.get(1))!
    const courses = await db.courses.toArray()
    expect(courses.filter((course) => inWeek(course, 2)).length).toBeGreaterThan(0)
    expect(courses.filter((course) => inWeek(course, 3)).length).toBeGreaterThan(0)
    expect(await loadPrefs()).toMatchObject({ startView: 'cards', themeMode: 'dark', visibleDays: [1, 2, 3, 4, 5] })
    await db.timetables.update(1, { startDate: '2000-01-03' })
    await db.courses.clear()
    await seedDemoTable()
    expect((await db.timetables.get(1))!.startDate).toBe(table.startDate)
    expect(await db.courses.count()).toBe(9)
    expect(await real.table('prefs').get('sentinel')).toEqual({ key: 'sentinel', value: 'real-user' })
    real.close()
  })

  it('keeps embedded overlays entirely out of browser history', async () => {
    const { useBackStack, installBackHandler } = await import('./state/backStack')
    const push = vi.spyOn(history, 'pushState')
    const replace = vi.spyOn(history, 'replaceState')
    const back = vi.spyOn(history, 'back')
    const onPop = vi.fn()
    const dispose = installBackHandler(onPop)
    const store = useBackStack.getState()
    store.pushTab('schedule')
    store.replaceTab('schedule')
    store.push('courseDetail')
    store.pop()
    expect(onPop).toHaveBeenCalledWith('courseDetail', '')
    store.push('weekJump')
    store.replace('courseDetail')
    store.popToRoot()
    expect(useBackStack.getState().stack).toEqual([])
    expect(push).not.toHaveBeenCalled()
    expect(replace).not.toHaveBeenCalled()
    expect(back).not.toHaveBeenCalled()
    dispose()
    vi.restoreAllMocks()
  })
})
